CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE items (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    category_id NUMBER NOT NULL,
    item_name VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    location VARCHAR2(150) NOT NULL,
    item_type VARCHAR2(10) NOT NULL,
    item_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    reported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_items_user
        FOREIGN KEY (user_id) REFERENCES users(user_id),

    CONSTRAINT fk_items_category
        FOREIGN KEY (category_id) REFERENCES categories(category_id),

    CONSTRAINT chk_item_type
        CHECK (item_type IN ('LOST', 'FOUND')),

    CONSTRAINT chk_item_status
        CHECK (item_status IN ('OPEN', 'CLAIMED', 'RETURNED'))
);


CREATE TABLE claims (
    claim_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id NUMBER NOT NULL,
    claimant_id NUMBER NOT NULL,
    claim_details VARCHAR2(500) NOT NULL,
    claim_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    claimed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_claims_item
        FOREIGN KEY (item_id) REFERENCES items(item_id),

    CONSTRAINT fk_claims_user
        FOREIGN KEY (claimant_id) REFERENCES users(user_id),

    CONSTRAINT chk_claim_status
        CHECK (claim_status IN ('PENDING', 'APPROVED', 'REJECTED'))
);


CREATE TABLE item_images (
    image_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id NUMBER NOT NULL,
    image_path VARCHAR2(255) NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_images_item
        FOREIGN KEY (item_id) REFERENCES items(item_id)
);


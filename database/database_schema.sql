CREATE OR REPLACE PROCEDURE count_items_by_type
AS
    v_lost  NUMBER;
    v_found NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_lost
    FROM items
    WHERE item_type = 'LOST';

    SELECT COUNT(*)
    INTO v_found
    FROM items
    WHERE item_type = 'FOUND';

    DBMS_OUTPUT.PUT_LINE('Lost Items: ' || v_lost);
    DBMS_OUTPUT.PUT_LINE('Found Items: ' || v_found);
END;
/

SET SERVEROUTPUT ON;

